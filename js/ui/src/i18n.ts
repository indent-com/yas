const completeEn: Messages = { ...en, ...enSupplement };
const locales: Record<string, Messages> = {
  en: completeEn,
  es,
  fr,
  de,
  ja,
  zh,
};

function detectLocale(): string {
  const lang =
    (typeof navigator !== "undefined" ? navigator.language : "en")?.split(
      "-",
    )[0] ?? "en";
  return lang in locales ? lang : "en";
}

const messages = locales[detectLocale()] ?? completeEn;

export function t(key: string): string {
  return messages[key] ?? completeEn[key] ?? key;
}

export function tp(
  key: string,
  params: Record<string, string | number>,
): string {
  let msg = t(key);
  for (const [k, v] of Object.entries(params)) {
    msg = msg.split(`{${k}}`).join(String(v));
  }
  return msg;
}
